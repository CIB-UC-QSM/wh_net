import math
import os
import re

import torch
import torch.nn.functional as F
from torch.utils.data import DataLoader, Dataset

from utils import continuous_dipole_kernel, imshow_3d


SPATIAL = (-3, -2, -1)


def complex_gaussian_noisy_phase(phase, magnitude, noise_std, generator=None):
    """Add circular complex Gaussian noise to ``magnitude * exp(-1j*phase)``."""
    signal = torch.polar(magnitude, -phase)
    noise_real = torch.randn(
        phase.shape,
        dtype=phase.dtype,
        device=phase.device,
        generator=generator,
    )
    noise_imag = torch.randn(
        phase.shape,
        dtype=phase.dtype,
        device=phase.device,
        generator=generator,
    )
    complex_noise = torch.complex(noise_real, noise_imag) * noise_std
    noisy_signal = signal + complex_noise
    return -torch.angle(noisy_signal)


def sparse_outlier_noise_std(
    base_noise_std,
    mask,
    probability=0.1,
    voxel_count=(1, 3),
    factor_range=(10.0, 100.0),
    generator=None,
):
    """Build a noise-STD map with rare, distinct high-noise ROI voxels."""
    probability = float(probability)
    voxel_count = tuple(int(value) for value in voxel_count)
    factor_range = tuple(float(value) for value in factor_range)
    if not 0.0 <= probability <= 1.0:
        raise ValueError("probability must be between zero and one.")
    if (
        len(voxel_count) != 2
        or voxel_count[0] < 1
        or voxel_count[0] > voxel_count[1]
    ):
        raise ValueError("voxel_count must be a positive (minimum, maximum) range.")
    if (
        len(factor_range) != 2
        or factor_range[0] <= 0
        or factor_range[0] > factor_range[1]
    ):
        raise ValueError("factor_range must be a positive (minimum, maximum) range.")

    base = torch.as_tensor(
        base_noise_std, dtype=mask.dtype, device=mask.device
    )
    noise_std = torch.ones_like(mask) * base
    if probability == 0.0:
        return noise_std
    if probability < 1.0 and torch.rand(
        (), device=mask.device, generator=generator
    ).item() >= probability:
        return noise_std

    eligible = torch.nonzero(mask.reshape(-1) > 0, as_tuple=False).flatten()
    if eligible.numel() == 0:
        return noise_std
    requested = int(torch.randint(
        voxel_count[0],
        voxel_count[1] + 1,
        (),
        device=mask.device,
        generator=generator,
    ).item())
    selected_count = min(requested, eligible.numel())
    # Only one to three offsets are needed. Rejection sampling avoids creating
    # a full random permutation of a potentially multi-million-voxel ROI.
    selected_offsets = torch.empty(
        0, dtype=torch.long, device=mask.device
    )
    while selected_offsets.numel() < selected_count:
        candidates = torch.randint(
            eligible.numel(),
            (selected_count,),
            device=mask.device,
            generator=generator,
        )
        selected_offsets = torch.unique(
            torch.cat((selected_offsets, candidates))
        )[:selected_count]
    selected = eligible[selected_offsets]
    factors = torch.empty(
        selected_count, dtype=mask.dtype, device=mask.device
    ).uniform_(factor_range[0], factor_range[1], generator=generator)
    noise_std.reshape(-1)[selected] *= factors
    return noise_std


def chi_texture_weight(chi, mask, invert=False):
    """Create a [0, 1] ROI texture from ``chi`` or its sign-inverted image."""
    texture = -chi if invert else chi
    inside = mask > 0
    if not torch.any(inside):
        return torch.zeros_like(chi)

    roi_values = texture[inside]
    value_min = roi_values.min()
    value_range = roi_values.max() - value_min
    if value_range <= torch.finfo(texture.dtype).eps:
        return 0.5 * mask.to(dtype=texture.dtype)

    weight = (texture - value_min) / value_range
    return weight.clamp(0.0, 1.0) * mask


def build_weight_map(chi, mask, use_mask=False, invert=False):
    """Return either the binary mask or a normalized susceptibility texture."""
    if use_mask:
        return mask.to(dtype=chi.dtype).clamp(0.0, 1.0)
    return chi_texture_weight(chi, mask, invert=invert)


class QSMDataset(Dataset):
    """Synthetic QSM samples with susceptibility-derived magnitude textures.

    Files generated by the current data pipeline contain four augmentations of
    each of 105 source subjects. The numeric suffix modulo source_id_modulus is
    exposed through group_ids so training can split by subject rather than by
    augmented volume. By default, 10% of samples also contain one to three
    randomly located ROI voxels whose complex-noise standard deviation is
    multiplied by an independently sampled factor between 10 and 100.
    """

    def __init__(self, data_dir="train_data", training=True, seed=0,
                 source_id_modulus=105, background_scale=(0.1, 9),
                 global_scale=(0.3, 5.0),
                 tv_regularization=(0.0, 0.01), tv_probability=0.5,
                 mask_weight_probability=0.7,
                 noise_outlier_probability=0.1,
                 noise_outlier_voxel_count=(1, 3),
                 noise_outlier_factor=(10.0, 100.0),
                 device=None):
        self.chi_files = sorted(
            os.path.join(data_dir, name)
            for name in os.listdir(data_dir)
            if name.startswith("image_") and name.endswith(".pt")
        )
        self.msk_files = sorted(
            os.path.join(data_dir, name)
            for name in os.listdir(data_dir)
            if name.startswith("mask_") and name.endswith(".pt")
        )
        if len(self.chi_files) != len(self.msk_files):
            raise RuntimeError(
                f"Number of image volumes ({len(self.chi_files)}) does not match "
                f"number of masks ({len(self.msk_files)})."
            )
        if not self.chi_files:
            raise RuntimeError(f"No image_*.pt / mask_*.pt pairs found in {data_dir!r}.")

        self.training = bool(training)
        self.seed = int(seed)
        self.device = torch.device("cpu" if device is None else device)
        if self.device.type == "cuda" and not torch.cuda.is_available():
            raise RuntimeError("A CUDA dataset device was requested, but CUDA is unavailable.")
        self.background_scale = tuple(float(x) for x in background_scale)
        if (
            len(self.background_scale) != 2
            or self.background_scale[0] <= 0
            or self.background_scale[0] > self.background_scale[1]
        ):
            raise ValueError("background_scale must be a positive (low, high) range.")
        self.background_log_scale = tuple(math.log(x) for x in self.background_scale)
        self.global_scale = tuple(float(x) for x in global_scale)
        if (
            len(self.global_scale) != 2
            or self.global_scale[0] <= 0
            or self.global_scale[0] > self.global_scale[1]
        ):
            raise ValueError("global_scale must be a positive (low, high) range.")
        self.global_log_scale = tuple(math.log(x) for x in self.global_scale)
        self.tv_regularization = tuple(float(x) for x in tv_regularization)
        if (
            len(self.tv_regularization) != 2
            or self.tv_regularization[0] < 0
            or self.tv_regularization[0] > self.tv_regularization[1]
        ):
            raise ValueError(
                "tv_regularization must be a non-negative (low, high) range."
            )
        self.tv_probability = float(tv_probability)
        if not 0.0 <= self.tv_probability <= 1.0:
            raise ValueError("tv_probability must be between zero and one.")
        self.mask_weight_probability = float(mask_weight_probability)
        if not 0.0 <= self.mask_weight_probability <= 1.0:
            raise ValueError(
                "mask_weight_probability must be between zero and one."
            )
        self.noise_outlier_probability = float(noise_outlier_probability)
        self.noise_outlier_voxel_count = tuple(
            int(value) for value in noise_outlier_voxel_count
        )
        self.noise_outlier_factor = tuple(
            float(value) for value in noise_outlier_factor
        )
        # Validate once at construction without consuming any random numbers.
        sparse_outlier_noise_std(
            1.0,
            torch.zeros(1, dtype=torch.float32, device=self.device),
            probability=0.0,
            voxel_count=self.noise_outlier_voxel_count,
            factor_range=self.noise_outlier_factor,
        )
        if not 0.0 <= self.noise_outlier_probability <= 1.0:
            raise ValueError(
                "noise_outlier_probability must be between zero and one."
            )
        self.group_ids = [
            self._group_id(path, source_id_modulus) for path in self.chi_files
        ]

        sample_shape = tuple(torch.load(self.chi_files[0], weights_only=True).shape[-3:])
        self.D = (
            torch.from_numpy(continuous_dipole_kernel(sample_shape))
            .unsqueeze(0)
            .float()
            .to(self.device)
        )

    @staticmethod
    def _group_id(path, modulus):
        match = re.search(r"_(\d+)\.pt$", os.path.basename(path))
        if match is None:
            return os.path.basename(path)
        file_id = int(match.group(1))
        return file_id % modulus if modulus is not None else file_id

    @staticmethod
    def _uniform(low, high, generator, device="cpu"):
        return torch.empty((), dtype=torch.float32, device=device).uniform_(
            low, high, generator=generator
        ).item()

    @staticmethod
    @torch.no_grad()
    def total_variation_cartoon(image, regularization_level):
        """Return the TV-denoised 3D cartoon component on ``image.device``."""
        if image.ndim != 3:
            raise ValueError(
                f"image must be 3D, but received a tensor with shape {tuple(image.shape)}."
            )

        regularization_level = float(regularization_level)
        if regularization_level < 0:
            raise ValueError("regularization_level must be non-negative.")
        if regularization_level == 0:
            return image.clone()

        # Chambolle's projection algorithm, implemented entirely with Torch so
        # CUDA inputs never round-trip through CPU/NumPy. Energy is checked in
        # small intervals to avoid synchronizing the GPU on every iteration.
        ndim = image.ndim
        dual = torch.zeros((ndim, *image.shape), dtype=image.dtype, device=image.device)
        gradient = torch.zeros_like(dual)
        divergence = torch.zeros_like(image)
        cartoon = image
        tau = 1.0 / (2.0 * ndim)
        energy_initial = None
        energy_previous = None

        for iteration in range(200):
            if iteration:
                divergence = -dual.sum(dim=0)
                divergence[1:, :, :] += dual[0, :-1, :, :]
                divergence[:, 1:, :] += dual[1, :, :-1, :]
                divergence[:, :, 1:] += dual[2, :, :, :-1]
                cartoon = image + divergence

            gradient.zero_()
            gradient[0, :-1, :, :] = cartoon[1:, :, :] - cartoon[:-1, :, :]
            gradient[1, :, :-1, :] = cartoon[:, 1:, :] - cartoon[:, :-1, :]
            gradient[2, :, :, :-1] = cartoon[:, :, 1:] - cartoon[:, :, :-1]
            norm = torch.linalg.vector_norm(gradient, dim=0, keepdim=True)

            dual.sub_(gradient, alpha=tau)
            dual.div_(norm.mul(tau / regularization_level).add_(1.0))

            if iteration % 5 == 0:
                energy = (
                    divergence.square().sum()
                    + regularization_level
                    * torch.linalg.vector_norm(gradient, dim=0).sum()
                ) / image.numel()
                if energy_initial is None:
                    energy_initial = energy
                elif torch.abs(energy_previous - energy) < 2e-4 * energy_initial:
                    break
                energy_previous = energy

        return cartoon

    @staticmethod
    def _smooth_noise(reference, generator, kernel_size):
        """Positive, unit-ROI-mean low-frequency confidence map."""
        noise = torch.randn(
            (1, *reference.shape),
            dtype=reference.dtype,
            device=reference.device,
            generator=generator,
        )
        smooth = F.avg_pool3d(
            noise, kernel_size=kernel_size, stride=1, padding=kernel_size // 2
        ).squeeze(0)
        count = reference.sum().clamp_min(1.0)
        mean = (smooth * reference).sum() / count
        variance = ((smooth - mean).square() * reference).sum() / count
        standardized = (smooth - mean) / variance.sqrt().clamp_min(1e-6)
        confidence = torch.exp(0.5 * standardized).clamp(0.1, 10.0)
        roi_mean = (confidence * reference).sum() / count
        noise = confidence / roi_mean.clamp_min(1e-6)
        return noise / noise.abs().max()

    def _generator(self, idx):
        if self.training:
            return None
        generator = torch.Generator(device=self.device)
        generator.manual_seed(self.seed + int(idx))
        return generator

    def __len__(self):
        return len(self.chi_files)

    def __getitem__(self, idx):
        generator = self._generator(idx)
        chi = (
            torch.load(self.chi_files[idx], weights_only=True)
            .float()
            .to(self.device)
        )
        mask = (
            torch.load(self.msk_files[idx], weights_only=True)
            .float()
            .to(self.device)
            .clamp(0.0, 1.0)
        )

        chi = chi * self._uniform(0.1, 3.0, generator, self.device)
        apply_tv = self._uniform(
            0.0, 1.0, generator, self.device
        ) < self.tv_probability
        if apply_tv:
            regularization_level = self._uniform(
                *self.tv_regularization, generator, self.device
            )
            chi = self.total_variation_cartoon(
                chi.squeeze(0), regularization_level
            ).unsqueeze(0)
        permutation = torch.randperm(3, generator=generator, device=self.device)
        dims = (0, *(axis + 1 for axis in permutation.cpu().tolist()))
        chi = chi.permute(dims).contiguous()
        mask = mask.permute(dims).contiguous()

        flip_dims = [
            dim for dim in (1, 2, 3)
            if torch.rand((), generator=generator, device=self.device).item() < 0.5
        ]
        if flip_dims:
            chi = torch.flip(chi, dims=flip_dims).contiguous()
            mask = torch.flip(mask, dims=flip_dims).contiguous()
        chi = chi * mask

        chi_k = torch.fft.fftn(chi, dim=SPATIAL)
        local = torch.fft.ifftn(self.D * chi_k, dim=SPATIAL).real * mask

        # Sources are separated from the ROI by a three-voxel shell, therefore
        # their field is harmonic inside the ROI. Most samples use a smooth
        # random exterior, while 30% retain uniform exterior susceptibility.
        dilated_mask = F.max_pool3d(
            mask.unsqueeze(0), kernel_size=7, stride=1, padding=3
        ).squeeze(0)
        exterior = 1.0 - dilated_mask
        use_constant_pattern = self._uniform(
            0.0, 1.0, generator, self.device
        ) < 0.3
        exterior_pattern = (
            torch.ones_like(mask)
            if use_constant_pattern
            else self._smooth_noise(mask, generator, kernel_size=13)
        )
        log_scale = self._uniform(
            *self.background_log_scale,
            generator,
            self.device,
        )
        exterior_chi = exterior * exterior_pattern * math.exp(log_scale)
        phi_h = torch.fft.ifftn(
            self.D * torch.fft.fftn(exterior_chi, dim=SPATIAL), dim=SPATIAL
        ).real * mask

        use_mask_weight = self._uniform(
            0.0, 1.0, generator, self.device
        ) < self.mask_weight_probability
        invert_weight_texture = (
            False
            if use_mask_weight
            else self._uniform(0.0, 1.0, generator, self.device) < 0.5
        )
        W = build_weight_map(
            chi,
            mask,
            use_mask=use_mask_weight,
            invert=invert_weight_texture,
        )
        local_max = local.abs().max()
        snr = self._uniform(20.0, 120.0, generator, self.device)
        base_noise_std = local_max / max(snr, 1e-6)
        noise_std = sparse_outlier_noise_std(
            base_noise_std,
            mask,
            probability=self.noise_outlier_probability,
            voxel_count=self.noise_outlier_voxel_count,
            factor_range=self.noise_outlier_factor,
            generator=generator,
        )
        clean_phase = mask * (local + phi_h)
        phase = mask * complex_gaussian_noisy_phase(
            clean_phase,
            W,
            noise_std,
            generator=generator,
        )

        # This changes numerical units only: signal, background, target and
        # noise realization all receive the same log-uniform multiplier.
        global_log_scale = self._uniform(
            *self.global_log_scale, generator, self.device
        )
        global_factor = math.exp(global_log_scale)
        phase = phase * global_factor
        chi = chi * global_factor
        phi_h = phi_h * global_factor

        return phase, mask, mask, self.D, chi, phi_h

