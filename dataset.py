if __name__ == "__main__":
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    dataset = QSMDataset(training=True, seed=90, device=device)
    dataloader = DataLoader(
        dataset, batch_size=1, shuffle=False, num_workers=0
    )
    phase, mask, W, D, chi_gt, phi_h = next(iter(dataloader))
    imshow_3d(phase.cpu().numpy()[0, 0], "phase", rango=(-0.1, 0.1), angles=(-90, -90, 90))
    imshow_3d(mask.cpu().numpy()[0, 0], "mask", rango=(0, 1), angles=(-90, -90, 90))
    imshow_3d(W.cpu().numpy()[0, 0], "W", rango=(0, 2), angles=(-90, -90, 90))
    imshow_3d(chi_gt.cpu().numpy()[0, 0], "chi_gt", rango=(-0.1, 0.1), angles=(-90, -90, 90))
    imshow_3d(phi_h.cpu().numpy()[0, 0], "phi_h", rango=(-0.1, 0.1), angles=(-90, -90, 90))

